# ─────────────────────────────────────────────────────────────────────────────
# Boundary-protected replacements  (Arabic character lookbehind/lookahead)
# ─────────────────────────────────────────────────────────────────────────────
BOUNDARY_TRANSLATIONS = [
    ('تواصل', 'Contact'),       # avoid matching inside متواصل
    ('لا', 'Non'),              # avoid matching inside آلاف, لاحقاً etc.
]


def translate(content: str) -> str:
    for ar, fr in TRANSLATIONS:
        content = content.replace(ar, fr)
    for ar, fr in BOUNDARY_TRANSLATIONS:
        pattern = f'(?<!{AR}){re.escape(ar)}(?!{AR})'
        content = re.sub(pattern, fr, content)
    return content


def process_file(src_path: str, dst_path: str):
    with open(src_path, 'r', encoding='utf-8') as f:
        content = f.read()
    content = translate(content)
    os.makedirs(os.path.dirname(dst_path), exist_ok=True)
    with open(dst_path, 'w', encoding='utf-8') as f:
        f.write(content)


def main():
    if os.path.exists(DST):
        shutil.rmtree(DST)
    count = 0
    for theme in sorted(os.listdir(SRC)):
        src_theme = os.path.join(SRC, theme)
        dst_theme = os.path.join(DST, theme)
        if not os.path.isdir(src_theme):
            continue
        for fname in os.listdir(src_theme):
            src_file = os.path.join(src_theme, fname)
            dst_file = os.path.join(dst_theme, fname)
            if fname.endswith(('.tsx', '.ts', '.js', '.jsx', '.css')):
                process_file(src_file, dst_file)
                count += 1
            else:
                os.makedirs(dst_theme, exist_ok=True)
                shutil.copy2(src_file, dst_file)
        print(f'  ✓ {theme}')
    print(f'\nDone — {count} files processed into {DST}')


if __name__ == '__main__':
    main()
